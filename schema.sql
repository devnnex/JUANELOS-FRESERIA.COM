create or replace function public.publish_order_event(p_order_id text, p_revision bigint, p_event_kind text default 'changed')
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.order_events(order_id, revision, event_kind)
  values(left(coalesce(p_order_id, ''), 80), greatest(coalesce(p_revision, 0), 0),
    case when p_event_kind in ('created', 'changed', 'deleted') then p_event_kind else 'changed' end);
  delete from public.order_events where created_at < now() - interval '24 hours';
  return true;
end;
$$;

create or replace function public.session_user_id(p_token text)
returns uuid
language sql
stable
security definer
set search_path = public, extensions
as $$
  select u.id
  from public.admin_sessions s
  join public.staff_users u on u.id = s.user_id
  where s.token_hash = encode(digest(coalesce(p_token, ''), 'sha256'), 'hex')
    and s.expires_at > now()
    and u.active
  limit 1;
$$;

create or replace function public.user_has_permission(p_user_id uuid, p_permission text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.staff_users u
    where u.id = p_user_id and u.active
      and (u.role = 'jefe' or coalesce((u.permissions ->> p_permission)::boolean, false))
  );
$$;

create or replace function public.bootstrap_status()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object('hasBoss', exists(select 1 from public.staff_users where role = 'jefe'));
$$;

create or replace function public.create_initial_boss(
  p_username text,
  p_display_name text,
  p_password text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_user public.staff_users;
  v_token text := encode(gen_random_bytes(32), 'hex');
begin
  if exists(select 1 from public.staff_users where role = 'jefe') then
    raise exception 'El jefe ya fue creado.';
  end if;
  if length(trim(p_username)) < 3 or length(p_password) < 8 or length(trim(p_display_name)) < 2 then
    raise exception 'Completa un usuario válido, nombre y contraseña de mínimo 8 caracteres.';
  end if;

  insert into public.staff_users (username, display_name, password_hash, role, permissions)
  values (
    lower(trim(p_username)), trim(p_display_name), crypt(p_password, gen_salt('bf', 10)), 'jefe',
    '{"products":true,"toppings":true,"payments":true,"neighborhoods":true,"orders":true,"users":true,"audit":true}'::jsonb
  ) returning * into v_user;

  insert into public.admin_sessions (user_id, token_hash, expires_at)
  values (v_user.id, encode(digest(v_token, 'sha256'), 'hex'), now() + interval '12 hours');
  insert into public.audit_log (user_id, user_name, action, entity, entity_id)
  values (v_user.id, v_user.display_name, 'crear_jefe', 'usuario', v_user.id::text);

  return jsonb_build_object('token', v_token, 'user', jsonb_build_object(
    'id', v_user.id, 'username', v_user.username, 'displayName', v_user.display_name,
    'role', v_user.role, 'permissions', v_user.permissions
  ));
exception when unique_violation then
  raise exception 'El usuario o el jefe ya existe.';
end;
$$;

create or replace function public.admin_login(p_username text, p_password text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_user public.staff_users;
  v_token text := encode(gen_random_bytes(32), 'hex');
begin
  select * into v_user from public.staff_users
  where lower(username) = lower(trim(p_username)) and active limit 1;
  if v_user.id is null or crypt(p_password, v_user.password_hash) <> v_user.password_hash then
    raise exception 'Usuario o contraseña incorrectos.';
  end if;

  delete from public.admin_sessions where expires_at <= now();
  insert into public.admin_sessions (user_id, token_hash, expires_at)
  values (v_user.id, encode(digest(v_token, 'sha256'), 'hex'), now() + interval '12 hours');
  update public.staff_users set last_login_at = now() where id = v_user.id;
  insert into public.audit_log (user_id, user_name, action, entity, entity_id)
  values (v_user.id, v_user.display_name, 'iniciar_sesion', 'sesion', v_user.id::text);

  return jsonb_build_object('token', v_token, 'user', jsonb_build_object(
    'id', v_user.id, 'username', v_user.username, 'displayName', v_user.display_name,
    'role', v_user.role, 'permissions', v_user.permissions
  ));
end;
$$;

