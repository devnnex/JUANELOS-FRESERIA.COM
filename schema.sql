create or replace function public.validate_admin_session(p_token text, p_permission text default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, extensions
as $$
declare
  v_id uuid := public.session_user_id(p_token);
  v_user public.staff_users;
begin
  if v_id is null then return jsonb_build_object('valid', false); end if;
  select * into v_user from public.staff_users where id = v_id;
  if p_permission is not null and not public.user_has_permission(v_id, p_permission) then
    return jsonb_build_object('valid', false, 'reason', 'permission');
  end if;
  return jsonb_build_object('valid', true, 'user', jsonb_build_object(
    'id', v_user.id, 'username', v_user.username, 'displayName', v_user.display_name,
    'role', v_user.role, 'permissions', v_user.permissions
  ));
end;
$$;

create or replace function public.admin_snapshot(p_token text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_id uuid := public.session_user_id(p_token);
  v_is_boss boolean;
begin
  if v_id is null then raise exception 'Sesión vencida.'; end if;
  select role = 'jefe' into v_is_boss from public.staff_users where id = v_id;
  return jsonb_build_object(
    'products', (select coalesce(jsonb_agg(to_jsonb(p) order by p.sort_order, p.name), '[]') from public.products p),
    'toppings', (select coalesce(jsonb_agg(to_jsonb(t) order by t.kind, t.sort_order, t.name), '[]') from public.toppings t),
    'payments', (select coalesce(jsonb_agg(to_jsonb(m) order by m.sort_order, m.name), '[]') from public.payment_methods m),
    'neighborhoods', (select coalesce(jsonb_agg(to_jsonb(n) order by n.sort_order, n.name), '[]') from public.neighborhoods n),
    'users', case when v_is_boss then (select coalesce(jsonb_agg(jsonb_build_object(
      'id', u.id, 'username', u.username, 'displayName', u.display_name, 'role', u.role,
      'permissions', u.permissions, 'active', u.active, 'createdAt', u.created_at, 'lastLoginAt', u.last_login_at
    ) order by u.role, u.display_name), '[]') from public.staff_users u) else '[]'::jsonb end
  );
end;
$$;

create or replace function public.admin_mutate(p_token text, p_entity text, p_action text, p_data jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_user_id uuid := public.session_user_id(p_token);
  v_user_name text;
  v_permission text;
  v_id text := coalesce(nullif(trim(p_data ->> 'id'), ''), encode(digest(random()::text || clock_timestamp()::text, 'sha256'), 'hex'));
begin
  v_permission := case p_entity
    when 'product' then 'products' when 'topping' then 'toppings'
    when 'payment' then 'payments' when 'neighborhood' then 'neighborhoods' else null end;
  if v_user_id is null or v_permission is null or not public.user_has_permission(v_user_id, v_permission) then
    raise exception 'No tienes permiso para realizar esta acción.';
  end if;
  select display_name into v_user_name from public.staff_users where id = v_user_id;

  if p_action = 'delete' then
    if p_entity = 'product' then delete from public.products where id = v_id;
    elsif p_entity = 'topping' then delete from public.toppings where id = v_id;
    elsif p_entity = 'payment' then delete from public.payment_methods where id = v_id;
    elsif p_entity = 'neighborhood' then delete from public.neighborhoods where id = v_id;
    end if;
  elsif p_action = 'save' then
    if p_entity = 'product' then
      insert into public.products (id,name,category,price,image_url,description,badge,featured,available,sort_order,modifiers)
      values (v_id, trim(p_data->>'name'), trim(p_data->>'category'), (p_data->>'price')::integer,
        coalesce(p_data->>'image_url',''), coalesce(p_data->>'description',''), coalesce(p_data->>'badge',''),
        coalesce((p_data->>'featured')::boolean,false), coalesce((p_data->>'available')::boolean,true),
        coalesce((p_data->>'sort_order')::integer,0), coalesce(p_data->'modifiers','[]'::jsonb))
      on conflict (id) do update set name=excluded.name, category=excluded.category, price=excluded.price,
        image_url=excluded.image_url, description=excluded.description, badge=excluded.badge,
        featured=excluded.featured, available=excluded.available, sort_order=excluded.sort_order, modifiers=excluded.modifiers;
    elsif p_entity = 'topping' then
      insert into public.toppings (id,name,kind,price,available,sort_order)
      values (v_id,trim(p_data->>'name'),p_data->>'kind',coalesce((p_data->>'price')::integer,0),coalesce((p_data->>'available')::boolean,true),coalesce((p_data->>'sort_order')::integer,0))
      on conflict (id) do update set name=excluded.name,kind=excluded.kind,price=excluded.price,available=excluded.available,sort_order=excluded.sort_order;
    elsif p_entity = 'payment' then
      insert into public.payment_methods (id,name,account_value,instructions,available,sort_order)
      values (v_id,trim(p_data->>'name'),coalesce(p_data->>'account_value',''),coalesce(p_data->>'instructions',''),coalesce((p_data->>'available')::boolean,true),coalesce((p_data->>'sort_order')::integer,0))
      on conflict (id) do update set name=excluded.name,account_value=excluded.account_value,instructions=excluded.instructions,available=excluded.available,sort_order=excluded.sort_order;
    elsif p_entity = 'neighborhood' then
      insert into public.neighborhoods (id,name,delivery_fee,available,sort_order)
      values (v_id,trim(p_data->>'name'),coalesce((p_data->>'delivery_fee')::integer,0),coalesce((p_data->>'available')::boolean,true),coalesce((p_data->>'sort_order')::integer,0))
      on conflict (id) do update set name=excluded.name,delivery_fee=excluded.delivery_fee,available=excluded.available,sort_order=excluded.sort_order;
    end if;
  else
    raise exception 'Acción no válida.';
  end if;

  insert into public.audit_log (user_id,user_name,action,entity,entity_id,details)
  values (v_user_id,v_user_name,p_action,p_entity,v_id,p_data - 'password');
  return jsonb_build_object('ok',true,'id',v_id);
end;
$$;

create or replace function public.admin_create_user(
  p_token text, p_username text, p_display_name text, p_password text, p_permissions jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_creator uuid := public.session_user_id(p_token);
  v_creator_name text;
  v_is_boss boolean;
  v_user public.staff_users;
begin
  select role = 'jefe' into v_is_boss from public.staff_users where id = v_creator;
  if v_creator is null or not coalesce(v_is_boss, false) then raise exception 'Solo el jefe puede crear usuarios.'; end if;
  if length(trim(p_username)) < 3 or length(p_password) < 8 or length(trim(p_display_name)) < 2 then raise exception 'Datos de usuario incompletos.'; end if;
  select display_name into v_creator_name from public.staff_users where id=v_creator;
  insert into public.staff_users(username,display_name,password_hash,role,permissions,created_by)
  values(lower(trim(p_username)),trim(p_display_name),crypt(p_password,gen_salt('bf',10)),'usuario',coalesce(p_permissions,'{}'::jsonb),v_creator)
  returning * into v_user;
  insert into public.audit_log(user_id,user_name,action,entity,entity_id,details)
  values(v_creator,v_creator_name,'crear','usuario',v_user.id::text,jsonb_build_object('username',v_user.username,'permissions',v_user.permissions));
  return jsonb_build_object('id',v_user.id,'username',v_user.username,'displayName',v_user.display_name,'permissions',v_user.permissions);
exception when unique_violation then raise exception 'Ese nombre de usuario ya existe.';
end;
$$;

create or replace function public.admin_set_user_active(p_token text, p_user_id uuid, p_active boolean)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare v_actor uuid := public.session_user_id(p_token); v_name text; v_is_boss boolean;
begin
  select role = 'jefe' into v_is_boss from public.staff_users where id = v_actor;
  if v_actor is null or not coalesce(v_is_boss, false) then raise exception 'Solo el jefe puede administrar usuarios.'; end if;
  if exists(select 1 from public.staff_users where id=p_user_id and role='jefe') then raise exception 'El jefe no puede desactivarse.'; end if;
  select display_name into v_name from public.staff_users where id=v_actor;
  update public.staff_users set active=p_active where id=p_user_id;
  if not p_active then delete from public.admin_sessions where user_id=p_user_id; end if;
  insert into public.audit_log(user_id,user_name,action,entity,entity_id,details) values(v_actor,v_name,'cambiar_estado','usuario',p_user_id::text,jsonb_build_object('active',p_active));
  return true;
end;
$$;

create or replace function public.admin_reset_user_password(p_token text, p_user_id uuid, p_password text)
returns boolean
language plpgsql
security definer
set search_path = public, extensions
as $$
declare v_actor uuid := public.session_user_id(p_token); v_name text; v_is_boss boolean;
begin
  select role = 'jefe' into v_is_boss from public.staff_users where id = v_actor;
  if v_actor is null or not coalesce(v_is_boss, false) then raise exception 'Solo el jefe puede cambiar contraseñas.'; end if;
  if length(p_password)<8 then raise exception 'La contraseña debe tener mínimo 8 caracteres.'; end if;
  select display_name into v_name from public.staff_users where id=v_actor;
  update public.staff_users set password_hash=crypt(p_password,gen_salt('bf',10)) where id=p_user_id;
  delete from public.admin_sessions where user_id=p_user_id;
  insert into public.audit_log(user_id,user_name,action,entity,entity_id) values(v_actor,v_name,'cambiar_clave','usuario',p_user_id::text);
  return true;
end;
$$;

